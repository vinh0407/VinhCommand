// Regenerate the explicit JSON codecs after changing persisted domain entities.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const files = ['agent','project','task','terminal','security','system'];
const sources = files.map(n => fs.readFileSync(path.join(root, 'lib/core/entities', n+'.dart'), 'utf8')).join('\n');
const enums = new Set([...sources.matchAll(/enum (\w+)/g)].map(m=>m[1]));
for (const f of fs.readdirSync(path.join(root,'lib/core/enums'))) {
  for (const m of fs.readFileSync(path.join(root,'lib/core/enums',f),'utf8').matchAll(/enum (\w+)/g)) enums.add(m[1]);
}
const wanted = new Set(['Agent','AgentAdapterConfig','Project','GitInfo','Workspace','Task','TaskLog','Terminal','TerminalOutput','Session','Device','AccessCode','WorkspacePermission','AuditEvent','Notification']);
function decode(t, x) {
  if(t.endsWith('?')) return `${x} == null ? null : ${decode(t.slice(0,-1),x)}`;
  if(['String','bool','int'].includes(t)) return `${x} as ${t}`;
  if(t==='double') return `(${x} as num).toDouble()`;
  if(t==='DateTime') return `DateTime.parse(${x} as String)`;
  if(t.endsWith('Id')) return `${t}(${x} as String)`;
  if(enums.has(t)) return `${t}.values.byName(${x} as String)`;
  if(t.startsWith('List<')) return `(${x} as List).map((v) => ${decode(t.slice(5,-1),'v')}).toList()`;
  if(t.startsWith('Map<')) return `${t}.from(${x} as Map)`;
  return `decode${t}(Map<String, dynamic>.from(${x} as Map))`;
}
function encode(t,x) {
  if(t.endsWith('?')) return `${x} == null ? null : ${encode(t.slice(0,-1),x+'!')}`;
  if(t==='DateTime') return `${x}.toIso8601String()`;
  if(t.endsWith('Id')) return `${x}.value`;
  if(enums.has(t)) return `${x}.name`;
  if(t.startsWith('List<')) return `${x}.map((v) => ${encode(t.slice(5,-1),'v')}).toList()`;
  if(t.startsWith('Map<') || ['String','bool','int','double'].includes(t)) return x;
  return `encode${t}(${x})`;
}
let out = "// Generated by tool/generate_codecs.cjs.\nimport '../../core/vinhcommand_core.dart';\n\n";
for(const m of sources.matchAll(/class (\w+) extends Equatable \{([\s\S]*?)(?=\nclass |\nenum |$)/g)) {
  const name=m[1]; if(!wanted.has(name)) continue;
  const fields=[...m[2].matchAll(/^  final ([\w<>, ?]+) (\w+);/gm)].map(m=>[m[1],m[2]]);
  out+=`Map<String, dynamic> encode${name}(${name} value) => {\n`;
  for(const [t,n] of fields) out+=`  '${n}': ${encode(t,'value.'+n)},\n`;
  out+=`};\n${name} decode${name}(Map<String, dynamic> row) => ${name}(\n`;
  for(const [t,n] of fields) out+=`  ${n}: ${decode(t,"row['"+n+"']")},\n`;
  out+=');\n\n';
}
fs.writeFileSync(path.join(root,'lib/infrastructure/database/entity_codecs.dart'),out);
